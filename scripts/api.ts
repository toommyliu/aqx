import { readFileSync, writeFileSync } from "node:fs";

const emitted = new URL("../target/api/mira.d.ts", import.meta.url);
const committed = new URL("../api/mira.d.ts", import.meta.url);
const header = "// Generated from crates/mira-script/src/mira.ts by `npm run api`. Do not edit this file.\n\n";
const text = header + readFileSync(emitted, "utf8");

function read(file: URL): string {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return "";
  }
}

if (process.argv.includes("--check")) {
  if (read(committed) !== text) {
    console.error("api/mira.d.ts is out of date. Run `npm run api` and commit the result.");
    process.exit(1);
  }
} else {
  writeFileSync(committed, text);
}
